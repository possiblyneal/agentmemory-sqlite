function item(over: Partial<ProbeItem> & { ref: string }): ProbeItem {
  return { kind: "observation", files: [], text: "", ...over };
}

function probe(kind: Probe["kind"], turn: number, items: ProbeItem[], over: Partial<Probe> = {}): Probe {
  return { kind, turn, latencyMs: 20, chars: items.reduce((n, i) => n + i.text.length, 0), items, ...over };
}

describe("scoreSession", () => {
  const earlier = session("e1", "2026-09-01T10:00:00Z", [
    { user: "build the cart" },
    { tool: "Edit", file: `${CWD}/src/cart.ts` },
    { user: "no, don't use raw sql strings in the repository layer, use the query builder" },
  ]);
  const current = session("c1", "2026-09-02T10:00:00Z", [
    { user: "extend the cart" },
    { tool: "Read", file: `${CWD}/src/cart.ts` },
    { user: "I told you, don't use raw sql strings in the repository layer, the query builder only" },
  ]);
  const key = deriveAnswerKey(current, [earlier]);

  it("credits a file delivered by session-start in time, and a late one not at all", () => {
    const early = scoreSession(current, key, [probe("session-start", 0, [item({ ref: "observation:o1", files: ["src/cart.ts"] })])]);
    expect(early.outcomes.find((o) => o.key.kind === "file")).toMatchObject({ injected: true, searched: false });
    const late = scoreSession(current, key, [probe("prompt-context", 2, [item({ ref: "observation:o1", files: ["src/cart.ts"] })])]);
    expect(late.outcomes.find((o) => o.key.kind === "file")).toMatchObject({ injected: false });
  });

  it("separates what search alone found from what an Injection delivered", () => {
    const s = scoreSession(current, key, [probe("search", 1, [item({ ref: "observation:o1", files: ["src/cart.ts"] })])]);
    expect(s.outcomes.find((o) => o.key.kind === "file")).toMatchObject({ injected: false, searched: true });
  });

  it("counts a repeated correction as prevented only when injected before the repeat", () => {
    const text = "no, don't use raw sql strings in the repository layer, use the query builder";
    const before = scoreSession(current, key, [probe("prompt-context", 1, [item({ ref: "observation:c", text })])]);
    expect(before.outcomes.find((o) => o.key.kind === "correction")?.injected).toBe(true);
    const atRepeat = scoreSession(current, key, [probe("prompt-context", 2, [item({ ref: "observation:c", text })])]);
    expect(atRepeat.outcomes.find((o) => o.key.kind === "correction")?.injected).toBe(false);
  });

  it("marks items used by file or by words, flags other-project items as leaks", () => {
    const s = scoreSession(current, key, [
      probe("session-start", 0, [
        item({ ref: "observation:a", files: ["src/cart.ts"], text: "edited cart" }),
        item({ ref: "observation:b", text: "unrelated gardening notes about tomatoes" }),
        item({ ref: "observation:c", project: "elsewhere", text: "deploy runbook" }),
      ]),
    ]);
    const byRef = Object.fromEntries(s.items.map((i) => [i.ref, i]));
    expect(byRef["observation:a"].used).toBe(true);
    expect(byRef["observation:b"].used).toBe(false);
    expect(byRef["observation:c"]).toMatchObject({ leak: true, used: false });
    expect(byRef["observation:a"].leak).toBe(false);
  });

  it("counts an item once however many probes returned it", () => {
    const i = item({ ref: "observation:a", text: "same" });
    const s = scoreSession(current, key, [probe("session-start", 0, [i]), probe("prompt-context", 1, [i])]);
    expect(s.items).toHaveLength(1);
    expect(s.items[0].firstTurn).toBe(0);
  });

  it("keeps failed probes out of latency", () => {
    const s = scoreSession(current, key, [probe("prompt-context", 1, [], { failed: true })]);
    expect(s.failedProbes).toBe(1);
    expect(s.latencies).toEqual([]);
  });
});

describe("summarizeReplay", () => {
  const earlier = session("e1", "2026-09-01T10:00:00Z", [{ user: "x" }, { tool: "Edit", file: `${CWD}/src/cart.ts` }]);
  const hit = session("c1", "2026-09-08T10:00:00Z", [{ user: "x" }, { tool: "Read", file: `${CWD}/src/cart.ts` }]);
  const miss = session("c2", "2026-09-15T10:00:00Z", [{ user: "x" }, { tool: "Read", file: `${CWD}/src/cart.ts` }]);

  const scores = [
    scoreSession(hit, deriveAnswerKey(hit, [earlier]), [
      probe("session-start", 0, [
        item({ ref: "observation:a", files: ["src/cart.ts"], text: "x".repeat(100) }),
        item({ ref: "observation:n", text: "noise", project: "other" }),
      ], { latencyMs: 2000 }),
      probe("prompt-context", 1, [], { latencyMs: 40 }),
    ]),
    scoreSession(miss, deriveAnswerKey(miss, [earlier, hit]), [probe("search", 1, [item({ ref: "observation:a", files: ["src/cart.ts"] })])]),
  ];
  const summary = summarizeReplay(scores, { storeBytesStart: 1000, storeBytesEnd: 3000 });

  it("scores each Goal line from the probes", () => {
    expect(summary.rightContent).toMatchObject({ injectedItems: 2, usedItems: 1, usedShare: 0.5 });
    expect(summary.rightContent.charsPerUsedItem).toBe(summary.rightContent.injectionChars);
    expect(summary.rightMoment.keyItems).toBe(2);
    expect(summary.rightMoment.injection).toEqual({ n: 2, hit: 1, share: 0.5 });
    expect(summary.rightMoment.search).toEqual({ n: 2, hit: 1, share: 0.5 });
    expect(summary.rightMoment.either.share).toBe(1);
    expect(summary.rightScope).toEqual({ injectedItems: 2, leaks: 1 });
    expect(summary.durableBeatsRecent.share).toBeNull();
    expect(summary.leastRecord).toEqual({ storeBytes: 3000, distinctUsedItems: 1, bytesPerUsedItem: 3000 });
  });

  it("reports latency percentiles against the hook timeout", () => {
    expect(summary.criticalPath["session-start"]).toEqual({ n: 1, p50: 2000, p99: 2000, overHookTimeout: 1 });
    expect(summary.criticalPath["prompt-context"]).toMatchObject({ n: 1, p50: 40, overHookTimeout: 0 });
  });

  it("scales store growth to replayed weeks", () => {
    expect(summary.operatorAttention.replayedWeeks).toBeCloseTo(1, 5);
    expect(summary.operatorAttention.growthBytesPerWeek).toBeCloseTo(2000, 3);
  });

  it("keeps terse-turn needs out of the headline and the worst cases", () => {
    const terse = session("c3", "2026-09-20T10:00:00Z", [
      { user: "plan how the cart total should round" },
      { user: "go ahead" },
      { tool: "Read", file: `${CWD}/src/cart.ts` },
    ]);
    const withTerse = [...scores, scoreSession(terse, deriveAnswerKey(terse, [earlier]), [])];
    const s = summarizeReplay(withTerse, { storeBytesStart: 1000, storeBytesEnd: 3000 });
    expect(s.rightMoment.keyItems).toBe(2);
    expect(s.rightMoment.byKind.file.injection.n).toBe(2);
    expect(s.rightMoment.terse.injection).toEqual({ n: 1, hit: 0, share: 0 });
    expect(worstCases(withTerse).filter((c) => c.category === "miss").map((c) => c.sessionId)).toEqual(["c2"]);
  });

  it("lists misses, noise and leaks with Session and turn", () => {
    const cases = worstCases(scores);
    expect(cases.filter((c) => c.category === "miss").map((c) => c.sessionId)).toEqual(["c2"]);
    expect(cases.filter((c) => c.category === "leak")).toHaveLength(1);
    expect(cases.every((c) => typeof c.turn === "number")).toBe(true);
  });
});

