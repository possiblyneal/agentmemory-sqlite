const CWD = "/synthetic/shop";

type Step =
  | { user: string; meta?: boolean }
  | { tool: string; file: string }
  | { toolResult: string };

function transcript(sessionId: string, start: string, steps: Step[]): string {
  const base = Date.parse(start);
  return steps
    .map((step, i) => {
      const common = { sessionId, cwd: CWD, timestamp: new Date(base + i * 1000).toISOString() };
      if ("user" in step) {
        return { ...common, type: "user", isMeta: step.meta, message: { role: "user", content: step.user } };
      }
      if ("tool" in step) {
        return {
          ...common,
          type: "assistant",
          message: {
            role: "assistant",
            content: [{ type: "tool_use", id: `t${i}`, name: step.tool, input: { file_path: step.file } }],
          },
        };
      }
      return {
        ...common,
        type: "user",
        message: { role: "user", content: [{ type: "tool_result", tool_use_id: "t0", content: step.toolResult }] },
      };
    })
    .map((e) => JSON.stringify(e))
    .join("\n");
}

function session(id: string, start: string, steps: Step[]): ReplaySession {
  const parsed = parseTranscript(transcript(id, start, steps));
  if (!parsed) throw new Error("synthetic transcript has no user turn");
  return parsed;
}

describe("parseTranscript", () => {
  it("reads id, cwd, project, start, prompts and files with turn numbers", () => {
    const s = session("s1", "2026-09-01T10:00:00Z", [
      { user: "add a cart total" },
      { tool: "Read", file: `${CWD}/src/cart.ts` },
      { tool: "Edit", file: `${CWD}/src/cart.ts` },
      { user: "now the tests" },
      { tool: "Write", file: `${CWD}/test/cart.test.ts` },
    ]);
    expect(s.id).toBe("s1");
    expect(s.cwd).toBe(CWD);
    expect(s.project).toBe("shop");
    expect(s.startedAt).toBe("2026-09-01T10:00:00.000Z");
    expect(s.userTurns.map((t) => [t.turn, t.text])).toEqual([
      [1, "add a cart total"],
      [2, "now the tests"],
    ]);
    expect(s.fileUses).toEqual([
      { file: "src/cart.ts", turn: 1, mode: "read" },
      { file: "src/cart.ts", turn: 1, mode: "edit" },
      { file: "test/cart.test.ts", turn: 2, mode: "edit" },
    ]);
  });

  it("drops tool results, slash commands, meta turns, interrupts and files outside the project", () => {
    const s = session("s2", "2026-09-01T10:00:00Z", [
      { user: "<command-name>/clear</command-name>" },
      { user: "Caveat: the messages below were generated by the user" },
      { user: "skill body expanded by the harness", meta: true },
      { user: "[Request interrupted by user]" },
      { user: "real prompt" },
      { toolResult: "file contents" },
      { tool: "Read", file: "/etc/hosts" },
    ]);
    expect(s.userTurns.map((t) => t.text)).toEqual(["real prompt"]);
    expect(s.fileUses).toEqual([]);
  });

  it("takes the start time from the first human turn, not an untimestamped leading line", () => {
    const lines = [
      JSON.stringify({ type: "file-history-snapshot", sessionId: "s4", cwd: CWD }),
      transcript("s4", "2026-09-05T08:00:00Z", [{ user: "hello there" }]),
    ].join("\n");
    expect(parseTranscript(lines)?.startedAt).toBe("2026-09-05T08:00:00.000Z");
  });

  it("returns null for a transcript with no human turn", () => {
    expect(parseTranscript(transcript("s3", "2026-09-01T10:00:00Z", [{ toolResult: "x" }]))).toBeNull();
  });

  it("skips subagent transcript names", () => {
    expect(isMainTranscriptName("0f3a.jsonl")).toBe(true);
    expect(isMainTranscriptName("agent-ab12.jsonl")).toBe(false);
    expect(isMainTranscriptName("notes.md")).toBe(false);
  });
});

describe("answer key: files needed", () => {
  const earlier = session("e1", "2026-09-01T10:00:00Z", [
    { user: "build the cart" },
    { tool: "Edit", file: `${CWD}/src/cart.ts` },
    { tool: "Read", file: `${CWD}/src/money.ts` },
  ]);

  it("lists files the Session used that an earlier Session touched, with the first turn of use", () => {
    const current = session("c1", "2026-09-02T10:00:00Z", [
      { user: "first" },
      { tool: "Read", file: `${CWD}/src/new.ts` },
      { user: "second" },
      { tool: "Read", file: `${CWD}/src/money.ts` },
      { tool: "Edit", file: `${CWD}/src/money.ts` },
    ]);
    expect(filesNeeded(current, [earlier])).toEqual([
      { kind: "file", file: "src/money.ts", turn: 2, earlierSessionIds: ["e1"] },
    ]);
  });

  it("is empty when nothing overlaps", () => {
    const current = session("c2", "2026-09-02T10:00:00Z", [
      { user: "hi" },
      { tool: "Read", file: `${CWD}/src/other.ts` },
    ]);
    expect(filesNeeded(current, [earlier])).toEqual([]);
  });
});

describe("answer key: repeated corrections", () => {
  const first = session("e1", "2026-09-01T10:00:00Z", [
    { user: "write the migration" },
    { user: "no, don't use raw sql strings in the repository layer, use the query builder" },
  ]);

  it("flags a correction that repeats an earlier one", () => {
    const current = session("c1", "2026-09-02T10:00:00Z", [
      { user: "add the orders repository" },
      { user: "I told you, don't use raw sql strings in the repository layer, the query builder only" },
    ]);
    const [hit] = repeatedCorrections(current, [first]);
    expect(hit).toMatchObject({ kind: "correction", turn: 2, earlierSessionId: "e1", earlierTurn: 2 });
  });

  it("ignores a correction with no earlier match", () => {
    const current = session("c2", "2026-09-02T10:00:00Z", [
      { user: "no, stop adding comments to the generated config files" },
    ]);
    expect(repeatedCorrections(current, [first])).toEqual([]);
  });

  it("ignores a repeated topic that is not a correction", () => {
    const current = session("c3", "2026-09-02T10:00:00Z", [
      { user: "please look at raw sql strings in the repository layer and the query builder" },
    ]);
    expect(repeatedCorrections(current, [first])).toEqual([]);
  });

  it("detects correction phrasing and ignores pasted bulk text", () => {
    expect(isCorrection("No that's wrong")).toBe(true);
    expect(isCorrection("looks good, ship it")).toBe(false);
    expect(isCorrection(`don't ${"x".repeat(600)}`)).toBe(false);
  });
});

